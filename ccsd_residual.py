import numpy as np


def Eccsd(f, g, t1, t2):
    N = t2.shape[0]
    o = slice(0, N)
    v = slice(N, None)
    r = 1.0 * np.einsum('kc,kc->', t1, f[o, v], optimize=True)
    r += 0.25 * np.einsum('klcd,klcd->', t2, g[o, o, v, v], optimize=True)
    r += 0.5 * np.einsum('kc,ld,klcd->', t1, t1, g[o, o, v, v], optimize=True)
    return r


def Rccsdt1(f, g, t1, t2):
    N = t2.shape[0]
    o = slice(0, N)
    v = slice(N, None)
    r = 1.0 * np.einsum('ai->ia', f[v, o], optimize=True)
    r -= 1.0 * np.einsum('ka,ki->ia', t1, f[o, o], optimize=True)
    r += 1.0 * np.einsum('ic,ac->ia', t1, f[v, v], optimize=True)
    r += 1.0 * np.einsum('ikac,kc->ia', t2, f[o, v], optimize=True)
    r -= 1.0 * np.einsum('ic,ka,kc->ia', t1, t1, f[o, v], optimize=True)
    r -= 1.0 * np.einsum('kc,akci->ia', t1, g[v, o, v, o], optimize=True)
    r += 0.5 * np.einsum('klac,klci->ia', t2, g[o, o, v, o], optimize=True)
    r += 0.5 * np.einsum('ikcd,akcd->ia', t2, g[v, o, v, v], optimize=True)
    r += 1.0 * np.einsum('ka,lc,klci->ia', t1, t1, g[o, o, v, o], optimize=True)
    r += 1.0 * np.einsum('ic,kd,akcd->ia', t1, t1, g[v, o, v, v], optimize=True)
    r -= 0.5 * np.einsum('ic,klad,klcd->ia', t1, t2, g[o, o, v, v], optimize=True)
    r += 0.5 * np.einsum('ikcd,la,klcd->ia', t2, t1, g[o, o, v, v], optimize=True)
    r += 1.0 * np.einsum('ikac,ld,klcd->ia', t2, t1, g[o, o, v, v], optimize=True)
    r -= 1.0 * np.einsum('ic,ka,ld,klcd->ia', t1, t1, t1, g[o, o, v, v], optimize=True)
    return r


